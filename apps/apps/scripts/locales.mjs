import { readdir, readFile, rename, rm, writeFile } from 'node:fs/promises';

const readJson = async path => JSON.parse(await readFile(path, 'utf8'));
const manifest = await readJson('app.json');
const files = await readdir('strings').catch(error => {
  if (error.code === 'ENOENT' && !manifest.strings?.base) return [];
  throw error;
});
const tags = files.filter(file => file.endsWith('.json')).map(file => file.slice(0, -5)).sort();
const preferredBase = manifest.strings?.base ?? 'en';
const base = tags.find(tag => tag.toLowerCase() === preferredBase.toLowerCase());
if ((tags.length || manifest.strings?.base) && !base) throw Error(`strings/${preferredBase}.json is required`);

// Exact checks message syntax and added placeholders. It allows omissions for fallback.
function placeholders(text) {
  const names = new Set();
  for (const [, name] of text.matchAll(/\\[{}\\]|\{\s*\$?([A-Za-z_][\w-]*)\s*\}/g)) {
    if (name) names.add(name);
  }
  return [...names].sort().join(',');
}

if (tags.length > 1) {
  const original = await readJson(`strings/${base}.json`);
  const messages = Object.entries(original).map(([key, text]) => [key, typeof text === 'string' ? placeholders(text) : null]);
  const problems = [];
  for (const tag of tags) {
    if (tag === base) continue;
    const catalog = await readJson(`strings/${tag}.json`);
    for (const [key, expected] of messages) {
      const translated = catalog?.[key];
      if (!Object.hasOwn(catalog ?? {}, key) || typeof translated !== 'string' || !translated.trim()) {
        problems.push(`strings/${tag}.json: missing translation for ${key}`);
      } else if (expected !== null && expected !== placeholders(translated)) {
        problems.push(`strings/${tag}.json: placeholder mismatch for ${key}`);
      }
    }
  }
  if (problems.length) throw Error(problems.join('\n'));
}

const languages = tags.map(tag => ({ tag, label: new Intl.DisplayNames([tag], { type: 'language' }).of(tag) ?? tag }));
const output = `// Generated by scripts/locales.mjs from strings/*.json.\nexport const languages = ${JSON.stringify(languages)};\n`;
const path = 'locales.generated.ts';
const previous = await readFile(path, 'utf8').catch(error => {
  if (error.code === 'ENOENT') return '';
  throw error;
});
if (previous !== output) {
  const staging = `${path}.${process.pid}`;
  try {
    await writeFile(staging, output);
    await rename(staging, path);
  } finally {
    await rm(staging, { force: true });
  }
}
